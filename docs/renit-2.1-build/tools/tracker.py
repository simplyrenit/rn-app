#!/usr/bin/env python3
"""Rebuild ../tracker.md from ../figma/index.tsv, the diff results in ../diffs/<platform>/<frameId>.json
and the manual notes in ../tracker-notes.tsv (frameId, platform, status, note).

Status per platform: pass / fail (from the latest diff), or a manual status from tracker-notes.tsv
(pending, blocked, n/a ...), else "todo". A note of n/a or pending wins over an older diff. Run after every diff: python3 tools/tracker.py
"""
import csv, json, os, collections

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STORY = {'00': 'ENG-426', '01': 'ENG-427', '02': 'ENG-428', '03': 'ENG-427', '04': 'ENG-429', '05': 'ENG-430', '06': 'ENG-431',
         '07': 'ENG-432', '08': 'ENG-433', '09': 'ENG-434', '10': 'ENG-435', '11': 'ENG-436', '12': 'ENG-437',
         '13': 'ENG-438', '14': 'ENG-439', '02b': 'ENG-463'}
# Section 01 frames belong to the story that owns their screen.
STORY_01 = {'home': 'ENG-427', 'pdp': 'ENG-429', 'pdp-all-specs': 'ENG-429', 'list-reading': 'ENG-435',
            'list-review': 'ENG-435', 'booking-rental-active': 'ENG-431', 'booking-details-view': 'ENG-431',
            'shop-today': 'ENG-433', 'shop-bookings': 'ENG-433'}


def story_of(r):
    """The flow story that owns an index.tsv row (frame_diff.py --story uses it too)."""
    return STORY_01.get(r['frameName'].split(' · ')[0], 'ENG-427') if r['section'] == '01' else STORY[r['section']]


def main():
    rows = list(csv.DictReader(open(os.path.join(ROOT, 'figma/index.tsv')), delimiter='\t'))
    notes = collections.defaultdict(dict)
    np = os.path.join(ROOT, 'tracker-notes.tsv')
    if os.path.exists(np):
        for r in csv.reader(open(np), delimiter='\t'):
            if r and not r[0].startswith('#') and len(r) >= 3:
                notes[r[0]][r[1]] = (r[2], r[3] if len(r) > 3 else '')

    def cell(fid, plat):
        # A retired frame (n/a) or one whose reference changed since its last diff (pending) is not judged by that diff.
        if notes.get(fid, {}).get(plat, ('',))[0] in ('n/a', 'pending'):
            return notes[fid][plat][0], ''
        p = os.path.join(ROOT, 'diffs', plat, fid.replace(':', '-') + '.json')
        if os.path.exists(p):
            d = json.load(open(p))
            st = 'pass' if d['pass'] else 'fail'
            if fid in notes and plat in notes[fid] and notes[fid][plat][0] in ('fail-heatmap',):
                st = 'fail'  # heat map rejected although % passed
            return st, f"{d['mismatch_pct']:.2f}%"
        if fid in notes and plat in notes[fid]:
            return notes[fid][plat][0], ''
        return 'todo', ''

    out, counts = [], collections.Counter()
    for r in rows:
        sec = r['section']
        story = story_of(r)
        i_st, i_pct = cell(r['frameId'], 'ios')
        a_st, a_pct = cell(r['frameId'], 'android')
        counts['ios ' + i_st] += 1
        counts['android ' + a_st] += 1
        note = '; '.join(v[1] for v in notes.get(r['frameId'], {}).values() if v[1])
        out.append(f"| {sec} | `{r['frameId']}` | {r['frameName']} | {story} | {r['check']} | {i_st} {i_pct} | {a_st} {a_pct} | {note} |")

    summary = ', '.join(f'{k}: {v}' for k, v in sorted(counts.items()))
    md = ['# Renit 2.1 build tracker (ENG-424)', '',
          'Generated by `tools/tracker.py` from `figma/index.tsv`, `diffs/` and `tracker-notes.tsv`. Do not edit by hand.',
          'Pass = mismatch ≤ 2% **and** a clean heat map (see README). Check: `live` on device, `fixture` via a dev-only state fixture, `devkit` on the dev-only kit screen (section 00), `jest` via a render test.',
          '', f'**Totals:** {summary}', '',
          '| Sec | Frame | Name | Story | Check | iOS | Android | Notes |', '|---|---|---|---|---|---|---|---|'] + out
    open(os.path.join(ROOT, 'tracker.md'), 'w').write('\n'.join(md) + '\n')
    print(summary)


if __name__ == '__main__':
    main()
