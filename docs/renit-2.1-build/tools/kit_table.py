#!/usr/bin/env python3
"""Write src/dev/kit-table.ts (DevKit's variant boxes) and print the 00 rows for figma/index.tsv,
both from the kit JSON in ../figma/00. Run after the kit export changes:

    python3 docs/renit-2.1-build/tools/kit_table.py            # writes the TS table
    python3 docs/renit-2.1-build/tools/kit_table.py --tsv      # prints the index.tsv rows

The numbers are Figma's, in pt, relative to the component set (or to the standalone component).
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
APP = os.path.dirname(os.path.dirname(ROOT))
KIT = os.path.join(ROOT, 'figma', '00')

# The kit nodes DevKit draws, in the order of the kit page. Tab bar and its two solid icons are
# diffed live on the tab roots; the Category icon map belongs to the category tile (ENG-427).
DEVKIT = ['2071:14418', '2071:14467', '2071:14471', '2071:14481', '2071:14501', '2073:14326',
          '2073:14341', '2073:14364', '2073:14380', '2073:14388', '2073:14413', '2074:14356',
          '2074:14388', '2074:14392', '2074:14416', '2074:14448', '2100:29942', '2110:30387']
LIVE = ['2071:14393', '2110:30274', '2110:30278']
TABS = {'Home': 'Home', 'Saved': 'Saved', 'Post': 'Post', 'Rentals': 'Rentals', 'Profile': 'Profile'}


def load(node_id):
    d = json.load(open(os.path.join(KIT, node_id.replace(':', '-') + '.json')))
    return d['nodes'][0], d['globalVars']['styles']


def solid(styles, ref):
    fills = styles.get(ref) if ref else None
    if isinstance(fills, list) and fills and fills[0].get('type') == 'SOLID':
        return fills[0]['color']
    return None


def home_indicator(node, depth=0):
    """Height of a drawn home-indicator strip at the node's bottom (bars and sheets), else 0."""
    for c in node.get('children', []):
        if c.get('name') == 'Home Indicator' and c.get('visible', True):
            return c['height']
        if depth < 1 and c.get('type') in ('INSTANCE', 'FRAME'):
            h = home_indicator(c, depth + 1)
            if h and abs(c['y'] + c['height'] - node['height']) < 0.01:
                return h
    return 0


def variants(node, styles):
    if node['type'] == 'COMPONENT_SET':
        return [dict(id=v['id'], name=v['name'], x=v['x'], y=v['y'], w=v['width'], h=v['height'],
                     # A square-cornered variant's own fill is drawn behind it (List row, Top bar): the
                     # components leave the canvas colour to the screen.
                     fill=None if v.get('cornerRadius') else solid(styles, v.get('fill')),
                     homeIndicator=home_indicator(v)) for v in node['children']]
    return [dict(id=node['id'], name=node['name'], x=0, y=0, w=node['width'], h=node['height'],
                 fill=None, homeIndicator=home_indicator(node))]


def ts():
    out = ['// Generated by docs/renit-2.1-build/tools/kit_table.py from docs/renit-2.1-build/figma/00/*.json.',
           '// Do not edit by hand; run the script again when the kit export changes.', '',
           'export type KitVariant = {',
           '  id: string;', '  name: string;',
           '  /** Box in the component set (or the standalone component), in pt. */',
           '  x: number;', '  y: number;', '  w: number;', '  h: number;',
           '  /** The variant\'s own fill, drawn behind a square-cornered variant. */',
           '  fill: string | null;',
           '  /** Height of the drawn home-indicator strip at the bottom; left out of the diff box. */',
           '  homeIndicator: number;', '};', '',
           'export type KitItem = { id: string; name: string; set: boolean; canvas: string; variants: KitVariant[] };',
           '', '// Exported so a release bundle that contained this module would show it (see README, release safety).',
           'export const RENIT_DEV_KIT_TABLE_MARKER = "RENIT_DEV_KIT_TABLE_MARKER";', '',
           'export const KIT: KitItem[] = [']
    for nid in DEVKIT:
        node, styles = load(nid)
        is_set = node['type'] == 'COMPONENT_SET'
        canvas = (solid(styles, node.get('fill')) or '#FFFFFF') if is_set else '#FFFFFF'
        out.append(f'  {{ id: {json.dumps(node["id"])}, name: {json.dumps(node["name"], ensure_ascii=False)}, '
                   f'set: {"true" if is_set else "false"}, canvas: "{canvas}", variants: [')
        for v in variants(node, styles):
            out.append(f'    {{ id: "{v["id"]}", name: {json.dumps(v["name"], ensure_ascii=False)}, x: {v["x"]:g}, '
                       f'y: {v["y"]:g}, w: {v["w"]:g}, h: {v["h"]:g}, '
                       f'fill: {json.dumps(v["fill"])}, homeIndicator: {v["homeIndicator"]:g} }},')
        out.append('  ] },')
    out.append('];')
    path = os.path.join(APP, 'src', 'dev', 'kit-table.ts')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w').write('\n'.join(out) + '\n')
    print('wrote', os.path.relpath(path, APP))


def tsv():
    for nid in DEVKIT + LIVE:
        node, styles = load(nid)
        slug = 'kit-' + node['name'].lower().split(' (')[0].replace(' · ', '-').replace('/', '-').replace(' ', '-')
        for v in variants(node, styles):
            state = v['name'] if node['type'] == 'COMPONENT_SET' else '-'
            name = f"{node['name']} · {state}" if state != '-' else node['name']
            if nid in LIVE:
                tab = v['name'].split('=')[-1] if nid == '2071:14393' else ('Post' if 'plus' in v['name'] else 'Rentals')
                route, check = f'MainTabs ({TABS[tab]} tab root)', 'live'
            else:
                route, check = 'DevKit', 'devkit'
            print('\t'.join([v['id'], '00', name, slug, route, state, check]))


if __name__ == '__main__':
    tsv() if '--tsv' in sys.argv else ts()
